export type CopyKey = keyof typeof copy.bg;

export function resolveLanguage(preference: "auto" | "bg" | "en"): AppLanguage {
  if (preference !== "auto") return preference;
  return navigator.language.toLowerCase().startsWith("bg") ? "bg" : "en";
}

export function translator(language: AppLanguage) {
  return (key: CopyKey, values?: Record<string, string | number>) => {
    let result: string = copy[language][key];
    for (const [name, value] of Object.entries(values ?? {})) {
      result = result.replace(`{${name}}`, String(value));
    }
    return result;
  };
}

